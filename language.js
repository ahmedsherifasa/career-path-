function getCurrentLanguage() {
  return localStorage.getItem("careerPathLanguage") || "ar";
}

function t(key) {
  const language = getCurrentLanguage();
  return translations[language][key] || key;
}

function setLanguage(language) {
  if (!translations[language]) return;

  localStorage.setItem("careerPathLanguage", language);

  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (translations[language][key]) {
      element.textContent = translations[language][key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.dataset.i18nPlaceholder;
    if (translations[language][key]) {
      element.placeholder = translations[language][key];
    }
  });

  const toggle = document.getElementById("languageToggle");
  if (toggle) {
    toggle.textContent = language === "ar" ? "English" : "العربية";
  }

  document.title = language === "ar"
    ? "Career Path | اختار مستقبلك"
    : "Career Path | Choose Your Future";

  document.body.classList.toggle("english", language === "en");

  if (typeof window.refreshCourseLanguage === "function") {
    window.refreshCourseLanguage();
  }
}

function toggleLanguage() {
  setLanguage(getCurrentLanguage() === "ar" ? "en" : "ar");
}

document.addEventListener("DOMContentLoaded", () => {
  const toggle = document.getElementById("languageToggle");
  if (toggle) {
    toggle.addEventListener("click", toggleLanguage);
  }

  setLanguage(getCurrentLanguage());
});
